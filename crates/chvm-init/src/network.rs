use std::process::Command;

pub fn setup_network() -> Result<(), Box<dyn std::error::Error>> {
    let ip_cmd = crate::helpers::find_binary("ip", &["/sbin/ip", "/chvm-bin/ip"]);

    // Bring up loopback
    run_ip(&ip_cmd, &["link", "set", "lo", "up"]);

    let cmdline = std::fs::read_to_string("/proc/cmdline").unwrap_or_default();
    let mut ip_addr = None;
    let mut gateway = None;

    for part in cmdline.split_whitespace() {
        if let Some(val) = part.strip_prefix("chvm.ip=") {
            ip_addr = Some(val.to_string());
        } else if ip_addr.is_none() {
            if let Some(val) = part.strip_prefix("ip=") {
                ip_addr = Some(val.to_string());
            }
        }

        if let Some(val) = part.strip_prefix("chvm.gw=") {
            gateway = Some(val.to_string());
        } else if gateway.is_none() {
            if let Some(val) = part.strip_prefix("gw=") {
                gateway = Some(val.to_string());
            }
        }
    }

    // Bring up eth0
    run_ip(&ip_cmd, &["link", "set", "eth0", "up"]);

    if let Some(ref addr) = ip_addr {
        println!("[init] Configuring network: ip={addr} gw={}", gateway.as_deref().unwrap_or("none"));

        run_ip(&ip_cmd, &["addr", "add", addr, "dev", "eth0"]);
        if let Some(ref gw) = gateway {
            run_ip(&ip_cmd, &["route", "add", "default", "via", gw]);
        }

        setup_dns();
    } else {
        println!("[init] No static IP configured, trying DHCP...");
        let dhcp_clients = ["/sbin/dhclient", "/usr/sbin/dhclient", "/sbin/udhcpc", "/bin/udhcpc"];
        let mut found = false;
        for d in &dhcp_clients {
            if std::path::Path::new(d).exists() {
                let _ = Command::new(d).arg("eth0").output();
                found = true;
                break;
            }
        }
        if !found {
            setup_dns();
        }
    }

    // Always ensure DNS
    if !std::path::Path::new("/etc/resolv.conf").exists() {
        setup_dns();
    }

    Ok(())
}

/// Run an `ip` command best-effort. No-op if ip binary was not found.
fn run_ip(ip_cmd: &Option<String>, args: &[&str]) {
    if let Some(ref ip) = ip_cmd {
        let _ = Command::new(ip).args(args).output();
    }
}

fn setup_dns() {
    let servers = crate::helpers::DNS_SERVERS;
    let config = format!(
        "# Generated by CHVM init\n{}",
        servers.iter().map(|s| format!("nameserver {s}\n")).collect::<String>()
    );
    match std::fs::write("/etc/resolv.conf", &config) {
        Ok(()) => println!("[init] DNS configured ({})", servers.join(", ")),
        Err(e) => eprintln!("[init] Warning: Failed to configure DNS: {e}"),
    }
}

#!/bin/bash
echo "================================"
echo "  Hello from chvm microVM!"
echo "================================"
echo ""
echo "Hostname : $(hostname)"
echo "Kernel   : $(uname -r)"
echo "Uptime   : $(cat /proc/uptime | awk '{print $1}')s"
echo "Memory   : $(free -m 2>/dev/null | awk '/Mem:/{print $2}' || echo 'N/A')MB"
echo "CPUs     : $(nproc)"
echo ""
echo "Network interfaces:"
ip -brief addr show 2>/dev/null || echo "  (ip command not available)"
echo ""
echo "Done."
